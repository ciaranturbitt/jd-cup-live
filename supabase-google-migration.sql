-- Run once in Supabase SQL Editor BEFORE deploying Google chat. Keeps existing comments/likes.
alter table public.cup_comments add column if not exists user_id uuid;
alter table public.cup_comments alter column manager_id drop not null;
alter table public.cup_comments alter column visitor_id drop not null;
create index if not exists cup_comments_user_recent_idx on public.cup_comments(user_id,created_at desc);
alter table public.cup_likes add column if not exists user_id uuid;
alter table public.cup_likes alter column visitor_id drop not null;
-- Existing primary key (comment_id,visitor_id) cannot accept NULL visitor_id.
alter table public.cup_likes drop constraint if exists cup_likes_pkey;
alter table public.cup_likes add column if not exists id bigint generated by default as identity;
alter table public.cup_likes add primary key (id);
create unique index if not exists cup_likes_google_unique on public.cup_likes(comment_id,user_id) where user_id is not null;
create unique index if not exists cup_likes_legacy_unique on public.cup_likes(comment_id,visitor_id) where visitor_id is not null;
